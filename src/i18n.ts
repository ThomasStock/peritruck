export type StringKey = keyof typeof STRINGS;
/** Copy in the current language, with `{{name}}` placeholders filled in. */
export function t(
  key: StringKey,
  vars: Record<string, string | number> = {},
  lang: Lang = current,
): string {
  return STRINGS[key][lang].replace(/\{\{(\w+)\}\}/g, (_, name: string) =>
    String(vars[name] ?? ""),
  );
}
/** Obstacle names stay English identifiers in the simulation; toasts translate them. */
export function obstacleName(name: string): string {
  const key = `obstacle.${name}`;
  return key in STRINGS ? t(key as StringKey) : name;
}
