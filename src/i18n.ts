/** Game copy in the four languages the game UI offers. DOM-free: the simulation
 * and the CLI import it too, so persistence and `<html lang>` live in main.ts.
 * The kiosk keeps its own production copy in `src/kiosk/i18n.ts`; the yard
 * operator's phone stays in the operator's language (English).
 */
export const LANGUAGES = [
  { code: "en", native: "English", english: "English", flag: "GB" },
  { code: "nl", native: "Nederlands", english: "Dutch", flag: "NL" },
  { code: "fr", native: "Français", english: "French", flag: "FR" },
  { code: "de", native: "Deutsch", english: "German", flag: "DE" },
] as const;
export type Lang = (typeof LANGUAGES)[number]["code"];
export const isLang = (x: unknown): x is Lang =>
  typeof x === "string" && LANGUAGES.some((l) => l.code === x);
export const DEFAULT_LANGUAGE: Lang = "en";
let current: Lang = DEFAULT_LANGUAGE;
export const language = () => current;
/** Module-wide: every later `t()` call, in the UI and the simulation, uses it. */
export function setLanguage(lang: Lang) {
  current = lang;
}
